-- ---------- PERSONAS ----------

-- Administradores. Se crean a mano con 06-admin.sql (nunca desde la web).
create table public.admins (
  id         uuid primary key references auth.users (id) on delete cascade,
  full_name  text not null,
  email      text not null unique,
  created_at timestamptz not null default now()
);

-- Clientes. La fila se crea SOLA al registrarse (trigger en 03-triggers.sql).
-- Mismas reglas de validación que checkout.js.
create table public.customers (
  id         uuid primary key references auth.users (id) on delete cascade,
  full_name  text not null default '',
  email      text,
  doc_number text check (doc_number ~ '^\d{6,10}$'),   -- cédula
  phone      text check (phone ~ '^3\d{9}$'),          -- celular colombiano
  department text,
  city       text,
  address    text,
  created_at timestamptz not null default now()
);

-- ---------- CATÁLOGO ----------

-- "by default" (no "always"): el seed puede usar los mismos ids de products.js
create table public.products (
  id           bigint generated by default as identity primary key,
  slug         text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name         text not null,
  description  text,
  type         text not null check (type in ('hoodie', 'crew', 'tee', 'cap')),
  collection   text check (collection in ('new', 'best')),   -- Novedades / Más vendidos
  color_name   text not null,
  price        bigint not null check (price > 0),             -- pesos, sin decimales
  sale_price   bigint check (sale_price > 0 and sale_price < price),
  tag          text,                                          -- 'Nuevo', '-15%', 'Últimas'...
  verse_text   text,
  verse_ref    text,
  image_main   text,                                          -- foto principal
  image_hover  text,                                          -- segunda vista
  is_available boolean not null default true,
  created_at   timestamptz not null default now()
);

-- Stock POR TALLA (en Supabase-1 era una sola columna "unidades").
-- Las gorras usan la talla 'Única'. Talla agotada = stock 0.
create table public.product_sizes (
  product_id bigint not null references public.products (id) on delete cascade,
  size       text not null check (size in ('S', 'M', 'L', 'XL', 'Única')),
  stock      integer not null default 0 check (stock >= 0),
  primary key (product_id, size)
);

-- ---------- ENVÍO Y CUPONES (antes estaban fijos en store.js) ----------

create table public.shipping_methods (
  code      text primary key,                         -- 'standard', 'express'
  label     text not null,
  price     bigint not null check (price >= 0),
  free_from bigint check (free_from > 0),             -- envío gratis desde este subtotal
  min_days  integer not null check (min_days >= 0),   -- días hábiles
  max_days  integer not null,
  is_active boolean not null default true,
  check (min_days <= max_days)
);

create table public.coupons (
  code                text primary key check (code = upper(code)),
  rate                numeric(4, 3) not null check (rate > 0 and rate <= 1),  -- 0.10 = 10%
  first_purchase_only boolean not null default false,
  is_active           boolean not null default true,
  expires_at          timestamptz,
  created_at          timestamptz not null default now()
);

-- ---------- PEDIDOS ----------
-- Estados (en Supabase-1: carrito, confirmado, enviado, entregado, cancelado):
--   cart            carrito abierto (uno por cliente)
--   pending_payment esperando la respuesta de la pasarela (07-payments-wompi.sql)
--   confirmed       pagado / contraentrega aceptada
--   preparing       empacando
--   shipped         entregado a la transportadora (en camino)
--   delivered       entregado al cliente
--   cancelled       cancelado (siempre con motivo)
create table public.orders (
  id           bigint generated always as identity primary key,
  order_number text generated always as ('EL-' || (1000 + id)) stored unique,  -- EL-1001
  customer_id  uuid not null references public.customers (id) on delete restrict,
  status       text not null default 'cart' check (status in (
                 'cart', 'pending_payment', 'confirmed', 'preparing',
                 'shipped', 'delivered', 'cancelled')),

  -- entrega (la llena checkout: confirm_order / start_payment)
  recipient_name  text,
  doc_number      text,
  phone           text,
  department      text,
  city            text,
  address         text,
  address_notes   text,
  shipping_method text references public.shipping_methods (code),
  shipping_cost   bigint not null default 0 check (shipping_cost >= 0),

  -- descuento
  coupon_code   text references public.coupons (code),
  discount_rate numeric(4, 3) not null default 0 check (discount_rate >= 0 and discount_rate <= 1),

  -- pago. NUNCA el número completo de la tarjeta ni el CVV.
  payment_method          text check (payment_method in ('card', 'pse', 'cod')),
  payment_label           text,     -- 'Tarjeta •••• 4242', 'PSE · Bancolombia'
  payment_provider        text check (payment_provider in ('wompi')),
  payment_reference       text unique,
  payment_transaction_id  text,
  payment_status          text check (payment_status in ('PENDING', 'APPROVED', 'DECLINED', 'VOIDED', 'ERROR')),
  payment_amount_in_cents bigint,
  paid_at                 timestamptz,

  -- cancelación
  cancel_reason text,

  -- fechas de cada paso (las pone el trigger de 03-triggers.sql)
  created_at   timestamptz not null default now(),
  checkout_at  timestamptz,
  confirmed_at timestamptz,
  preparing_at timestamptz,
  shipped_at   timestamptz,
  delivered_at timestamptz,
  cancelled_at timestamptz,

  -- motivos predeterminados (los mismos de Supabase-1)
  constraint orders_cancel_reason_check check (
    cancel_reason is null
    or (status = 'cancelled' and cancel_reason in (
      'Se agotó el stock del producto',
      'No pudimos confirmar el pago',
      'Dirección fuera de nuestra zona de entrega',
      'No pudimos contactarte para coordinar la entrega',
      'El producto llegó dañado a nuestra bodega',
      'Pedido duplicado',
      'Cancelado a solicitud del cliente',
      'Cancelado por el cliente'
    ))
  ),
  constraint orders_cancelled_needs_reason check (status <> 'cancelled' or cancel_reason is not null)
);

-- Un solo carrito abierto por cliente (el 23505 que maneja galeria.js)
create unique index orders_one_cart_per_customer on public.orders (customer_id) where status = 'cart';
create index orders_customer_id_idx on public.orders (customer_id);
create index orders_status_idx on public.orders (status);

-- Productos de cada pedido. unit_price queda vacío mientras es carrito:
-- lo fija la base al confirmar (es lo que se cobró, aunque luego cambie el precio).
create table public.order_items (
  id         bigint generated always as identity primary key,
  order_id   bigint not null references public.orders (id) on delete cascade,
  product_id bigint not null,
  size       text not null,
  quantity   integer not null check (quantity between 1 and 20),
  unit_price bigint check (unit_price >= 0),
  created_at timestamptz not null default now(),
  -- la talla tiene que existir para ese producto
  foreign key (product_id, size) references public.product_sizes (product_id, size) on delete restrict,
  -- la misma prenda en la misma talla es UNA línea (se suma la cantidad)
  unique (order_id, product_id, size)
);

create index order_items_order_id_idx on public.order_items (order_id);

-- Quién cambió qué y cuándo. changed_by vacío = el sistema (webhook de pagos).
create table public.order_status_history (
  id            bigint generated always as identity primary key,
  order_id      bigint not null references public.orders (id) on delete cascade,
  old_status    text,
  new_status    text not null,
  cancel_reason text,
  changed_by    uuid,
  changed_at    timestamptz not null default now()
);

create index order_status_history_order_id_idx on public.order_status_history (order_id);

-- ---------- VISTA CON TOTALES ----------
-- El total SIEMPRE lo calcula la base. Misma fórmula que store.js:
--   total = subtotal - round(subtotal * cupón) + envío
-- security_invoker: respeta el RLS de quien consulta.
-- OJO: "o.*" se fija al crear la vista. Si luego agregas columnas a orders,
-- hay que borrarla y crearla de nuevo (lección de motivo-cancelacion.sql).
create view public.orders_with_total
with (security_invoker = true)
as
select o.*,
       t.subtotal,
       t.item_count,
       round(t.subtotal * o.discount_rate)::bigint                         as discount,
       (t.subtotal - round(t.subtotal * o.discount_rate) + o.shipping_cost)::bigint as total
  from public.orders o
  cross join lateral (
    select coalesce(sum(i.quantity * i.unit_price), 0)::bigint as subtotal,
           coalesce(sum(i.quantity), 0)::integer              as item_count
      from public.order_items i
     where i.order_id = o.id
  ) t;
